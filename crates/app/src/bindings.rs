//! The frontend's types, written from this side (P6).
//!
//! Every struct that crosses the bridge derives `ts_rs::TS` where it is
//! declared, and `cargo test export_bindings` writes it into
//! `ui/src/lib/generated/` — see `.cargo/config.toml` for where that path comes
//! from. The frontend imports those files and never restates a field name, so
//! renaming a field in Rust is a TypeScript error in the UI rather than a
//! value that silently arrives as `undefined`.
//!
//! What ts-rs cannot carry is the handful of **constants** the two sides have
//! to agree on: a schema version, a default port, a worker count. They are not
//! types, so this module writes them, in the same run and into the same
//! directory. Small, but they are exactly the kind of number that is copied
//! once and then changed on one side only.

/// The generated constants, as TypeScript.
///
/// Hand-formatted rather than derived from anything: there is a handful of
/// them, each needs a sentence the Rust doc comment does not say the same way, and a
/// macro to save fifteen lines would be harder to read than the lines.
fn constants() -> String {
    format!(
        r#"// This file was generated from Rust. Do not edit this file manually.
//
// The values the two sides have to agree on but that are not types, so ts-rs
// has nothing to say about them. Written by `export_constants` in
// `crates/app/src/bindings.rs`.

/**
 * Schema version of the configuration file, sent on every save. Mirrors
 * `config::VERSION`; the backend refuses to reinterpret a file claiming a
 * higher one.
 */
export const CONFIG_VERSION = {version};

/**
 * The id the custom model is selected by. Mirrors `models::CUSTOM`. Not a
 * catalogue entry — there is nothing to download, only a path to point at —
 * but it sits in `model` so the picker has a single answer.
 */
export const CUSTOM_MODEL = "{custom}";

/**
 * Sidecars decoding in parallel when nobody has chosen. Mirrors
 * `pool::DEFAULT_WORKERS`: two, because parallel whisper instances share one
 * GPU and start to slow each other down well before the channel count is
 * reached.
 */
export const DEFAULT_WORKERS = {default_workers};

/**
 * The most the Settings page will ask for. Mirrors `pool::MAX_WORKERS`, which
 * clamps again on the way into a session — each worker is a separate process
 * holding its own copy of the model.
 */
export const MAX_WORKERS = {max_workers};

/**
 * What the LAN remote (P16) is served on when nothing has chosen. Mirrors
 * `remote::DEFAULT_PORT`.
 */
export const REMOTE_DEFAULT_PORT = {remote_port};

/**
 * The quietest an input trim goes, in decibels. Mirrors
 * `audio_core::gain::MIN_DB`, which clamps again on the way into a session —
 * the knob is not the only caller.
 */
export const GAIN_DB_MIN = {gain_min};

/**
 * The loudest, in decibels. Mirrors `audio_core::gain::MAX_DB`.
 */
export const GAIN_DB_MAX = {gain_max};
"#,
        version = crate::config::VERSION,
        custom = crate::models::CUSTOM,
        default_workers = crate::pool::DEFAULT_WORKERS,
        max_workers = crate::pool::MAX_WORKERS,
        remote_port = crate::remote::DEFAULT_PORT,
        gain_min = audio_core::gain::MIN_DB,
        gain_max = audio_core::gain::MAX_DB,
    )
}

/// Where the generated TypeScript goes.
///
/// The same directory ts-rs is pointed at, and read from the same environment
/// variable, so the two halves of the generation cannot end up writing to
/// different places. Relative to the workspace root, which is where cargo sets
/// it from `.cargo/config.toml`; `CARGO_MANIFEST_DIR` is this crate, two levels
/// below it.
fn export_dir() -> std::path::PathBuf {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(|p| p.parent())
        .expect("the crate sits two levels below the workspace root")
        .to_path_buf();
    root.join(option_env!("TS_RS_EXPORT_DIR").unwrap_or("ui/src/lib/generated"))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Named like ts-rs' own tests on purpose: `cargo test export_bindings`
    /// has to write *everything* the frontend imports, and a constants file
    /// that only appeared under a different filter is a file that would be
    /// stale in CI and current on the machine that last ran the full suite.
    #[test]
    fn export_bindings_constants() {
        let dir = export_dir();
        std::fs::create_dir_all(&dir).expect("the export directory");
        let path = dir.join("constants.ts");
        let contents = constants();

        // Only when it actually changed. `cargo test` runs on every check, and
        // rewriting a file Vite is watching restarts the dev server for no
        // reason.
        if std::fs::read_to_string(&path).is_ok_and(|current| current == contents) {
            return;
        }
        std::fs::write(&path, contents).expect("writing the constants");
    }
}
